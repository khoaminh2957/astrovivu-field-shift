/**
 * The handful of 4x4 operations the custom WebGL layers need. Column-major, like WebGL and like
 * the matrices MapLibre hands to custom layers. Kept local so the globe does not import a
 * transitive dependency of MapLibre directly.
 */
export type Mat4 = Float64Array;

export const identity = (): Mat4 => {
  const m = new Float64Array(16);
  m[0] = m[5] = m[10] = m[15] = 1;
  return m;
};

/** out = a * b (apply b first). */
export function multiply(out: Mat4, a: ArrayLike<number>, b: ArrayLike<number>): Mat4 {
  const r = new Float64Array(16);
  for (let c = 0; c < 4; c++) {
    for (let row = 0; row < 4; row++) {
      r[c * 4 + row] = a[row] * b[c * 4] + a[4 + row] * b[c * 4 + 1] + a[8 + row] * b[c * 4 + 2] + a[12 + row] * b[c * 4 + 3];
    }
  }
  out.set(r);
  return out;
}

function rotation(axis: 0 | 1 | 2, rad: number): Mat4 {
  const m = identity();
  const c = Math.cos(rad);
  const s = Math.sin(rad);
  const a = (axis + 1) % 3;
  const b = (axis + 2) % 3;
  m[a * 4 + a] = c;
  m[a * 4 + b] = s;
  m[b * 4 + a] = -s;
  m[b * 4 + b] = c;
  return m;
}

export const rotateX = (out: Mat4, m: ArrayLike<number>, rad: number): Mat4 => multiply(out, m, rotation(0, rad));
export const rotateY = (out: Mat4, m: ArrayLike<number>, rad: number): Mat4 => multiply(out, m, rotation(1, rad));
export const rotateZ = (out: Mat4, m: ArrayLike<number>, rad: number): Mat4 => multiply(out, m, rotation(2, rad));

/** General inverse (cofactor expansion). Returns false when the matrix is singular. */
export function invert(out: Mat4, m: ArrayLike<number>): boolean {
  const a00 = m[0], a01 = m[1], a02 = m[2], a03 = m[3];
  const a10 = m[4], a11 = m[5], a12 = m[6], a13 = m[7];
  const a20 = m[8], a21 = m[9], a22 = m[10], a23 = m[11];
  const a30 = m[12], a31 = m[13], a32 = m[14], a33 = m[15];
  const b00 = a00 * a11 - a01 * a10;
  const b01 = a00 * a12 - a02 * a10;
  const b02 = a00 * a13 - a03 * a10;
  const b03 = a01 * a12 - a02 * a11;
  const b04 = a01 * a13 - a03 * a11;
  const b05 = a02 * a13 - a03 * a12;
  const b06 = a20 * a31 - a21 * a30;
  const b07 = a20 * a32 - a22 * a30;
  const b08 = a20 * a33 - a23 * a30;
  const b09 = a21 * a32 - a22 * a31;
  const b10 = a21 * a33 - a23 * a31;
  const b11 = a22 * a33 - a23 * a32;
  let det = b00 * b11 - b01 * b10 + b02 * b09 + b03 * b08 - b04 * b07 + b05 * b06;
  if (!det) return false;
  det = 1 / det;
  out[0] = (a11 * b11 - a12 * b10 + a13 * b09) * det;
  out[1] = (a02 * b10 - a01 * b11 - a03 * b09) * det;
  out[2] = (a31 * b05 - a32 * b04 + a33 * b03) * det;
  out[3] = (a22 * b04 - a21 * b05 - a23 * b03) * det;
  out[4] = (a12 * b08 - a10 * b11 - a13 * b07) * det;
  out[5] = (a00 * b11 - a02 * b08 + a03 * b07) * det;
  out[6] = (a32 * b02 - a30 * b05 - a33 * b01) * det;
  out[7] = (a20 * b05 - a22 * b02 + a23 * b01) * det;
  out[8] = (a10 * b10 - a11 * b08 + a13 * b06) * det;
  out[9] = (a01 * b08 - a00 * b10 - a03 * b06) * det;
  out[10] = (a30 * b04 - a31 * b02 + a33 * b00) * det;
  out[11] = (a21 * b02 - a20 * b04 - a23 * b00) * det;
  out[12] = (a11 * b07 - a10 * b09 - a12 * b06) * det;
  out[13] = (a00 * b09 - a01 * b07 + a02 * b06) * det;
  out[14] = (a31 * b01 - a30 * b03 - a32 * b00) * det;
  out[15] = (a20 * b03 - a21 * b01 + a22 * b00) * det;
  return true;
}
